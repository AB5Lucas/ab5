ALTER TABLE public.rdos ADD COLUMN number bigint GENERATED BY DEFAULT AS IDENTITY;
WITH o AS (SELECT id, row_number() OVER (ORDER BY report_date, created_at) rn FROM public.rdos)
UPDATE public.rdos r SET number = o.rn FROM o WHERE o.id = r.id;
SELECT setval(pg_get_serial_sequence('public.rdos','number'), GREATEST((SELECT COALESCE(MAX(number),0) FROM public.rdos),1));
CREATE UNIQUE INDEX rdos_number_key ON public.rdos(number);