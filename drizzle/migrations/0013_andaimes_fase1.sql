-- Ajuste/entrada de estoque (delta pode ser negativo; nunca fica negativo)
CREATE OR REPLACE FUNCTION public.andam_adjust(_item uuid, _location text, _client uuid, _work uuid, _delta numeric, _note text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE cur numeric;
BEGIN
  IF NOT public.andam_can('/andaimes/estoque') THEN RAISE EXCEPTION 'Sem permissão'; END IF;
  PERFORM pg_advisory_xact_lock(hashtext('andam:' || _item));
  SELECT quantity INTO cur FROM andam_stock WHERE item_id = _item AND location = _location
    AND client_id IS NOT DISTINCT FROM _client AND work_id IS NOT DISTINCT FROM _work;
  IF coalesce(cur,0) + _delta < 0 THEN RAISE EXCEPTION 'Estoque insuficiente'; END IF;
  INSERT INTO andam_stock(item_id, location, client_id, work_id, quantity) VALUES (_item, _location, _client, _work, _delta)
  ON CONFLICT (item_id, location, client_id, work_id) DO UPDATE SET quantity = andam_stock.quantity + _delta, updated_at = now();
  INSERT INTO andam_movements(item_id, kind, to_location, to_client_id, to_work_id, quantity, notes)
  VALUES (_item, 'ajuste', _location, _client, _work, _delta, _note);
END $$;

CREATE OR REPLACE FUNCTION public.andam_transfer(_item uuid, _from_loc text, _from_client uuid, _from_work uuid, _to_loc text, _to_client uuid, _to_work uuid, _qty numeric, _note text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE cur numeric;
BEGIN
  IF NOT public.andam_can('/andaimes/estoque') THEN RAISE EXCEPTION 'Sem permissão'; END IF;
  IF _qty <= 0 THEN RAISE EXCEPTION 'Quantidade inválida'; END IF;
  PERFORM pg_advisory_xact_lock(hashtext('andam:' || _item));
  SELECT quantity INTO cur FROM andam_stock WHERE item_id = _item AND location = _from_loc
    AND client_id IS NOT DISTINCT FROM _from_client AND work_id IS NOT DISTINCT FROM _from_work;
  IF coalesce(cur,0) < _qty THEN RAISE EXCEPTION 'Estoque insuficiente na origem'; END IF;
  UPDATE andam_stock SET quantity = quantity - _qty, updated_at = now() WHERE item_id = _item AND location = _from_loc
    AND client_id IS NOT DISTINCT FROM _from_client AND work_id IS NOT DISTINCT FROM _from_work;
  INSERT INTO andam_stock(item_id, location, client_id, work_id, quantity) VALUES (_item, _to_loc, _to_client, _to_work, _qty)
  ON CONFLICT (item_id, location, client_id, work_id) DO UPDATE SET quantity = andam_stock.quantity + _qty, updated_at = now();
  INSERT INTO andam_movements(item_id, kind, from_location, from_client_id, from_work_id, to_location, to_client_id, to_work_id, quantity, notes)
  VALUES (_item, 'transferencia', _from_loc, _from_client, _from_work, _to_loc, _to_client, _to_work, _qty, _note);
END $$;

CREATE OR REPLACE FUNCTION public.andam_finalize_inventory(_inv uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE inv record; r record; diff numeric;
BEGIN
  IF NOT public.andam_can('/andaimes/inventario') THEN RAISE EXCEPTION 'Sem permissão'; END IF;
  SELECT * INTO inv FROM andam_inventory WHERE id = _inv FOR UPDATE;
  IF inv.status <> 'em_andamento' THEN RAISE EXCEPTION 'Inventário não está em andamento'; END IF;
  FOR r IN SELECT * FROM andam_inventory_items WHERE inventory_id = _inv AND counted_qty IS NOT NULL LOOP
    IF r.counted_qty < 0 THEN RAISE EXCEPTION 'Quantidade contada negativa'; END IF;
    PERFORM pg_advisory_xact_lock(hashtext('andam:' || r.item_id));
    SELECT coalesce(sum(quantity),0) INTO diff FROM andam_stock WHERE item_id = r.item_id AND location = 'obra'
      AND client_id = inv.client_id AND work_id IS NOT DISTINCT FROM inv.work_id;
    UPDATE andam_inventory_items SET system_qty = diff WHERE id = r.id;
    diff := r.counted_qty - diff;
    INSERT INTO andam_stock(item_id, location, client_id, work_id, quantity) VALUES (r.item_id, 'obra', inv.client_id, inv.work_id, r.counted_qty)
    ON CONFLICT (item_id, location, client_id, work_id) DO UPDATE SET quantity = r.counted_qty, updated_at = now();
    IF diff <> 0 THEN
      INSERT INTO andam_movements(item_id, kind, to_location, to_client_id, to_work_id, quantity, inventory_id, notes)
      VALUES (r.item_id, 'ajuste_inventario', 'obra', inv.client_id, inv.work_id, diff, _inv, 'Inventário nº ' || inv.number);
    END IF;
  END LOOP;
  UPDATE andam_inventory SET status = 'finalizado', finalized_at = now(), finalized_by = auth.uid(), updated_at = now() WHERE id = _inv;
END $$;

REVOKE EXECUTE ON FUNCTION public.andam_adjust, public.andam_transfer, public.andam_finalize_inventory FROM anon, public;
GRANT EXECUTE ON FUNCTION public.andam_adjust, public.andam_transfer, public.andam_finalize_inventory, public.andam_can TO authenticated;

