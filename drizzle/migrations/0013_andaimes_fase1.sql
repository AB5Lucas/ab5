CREATE TABLE public.andam_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code text, name text NOT NULL, category text, unit text NOT NULL DEFAULT 'un',
  description text, min_stock numeric NOT NULL DEFAULT 0, active boolean NOT NULL DEFAULT true, notes text,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.andam_stock (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  item_id uuid NOT NULL REFERENCES public.andam_items(id) ON DELETE CASCADE,
  location text NOT NULL CHECK (location IN ('central','obra','transito','manutencao','danificado','retorno')),
  client_id uuid REFERENCES public.clients(id),
  work_id uuid REFERENCES public.works(id),
  quantity numeric NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE NULLS NOT DISTINCT (item_id, location, client_id, work_id)
);
CREATE TABLE public.andam_movements (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  item_id uuid NOT NULL REFERENCES public.andam_items(id) ON DELETE CASCADE,
  kind text NOT NULL,
  from_location text, from_client_id uuid, from_work_id uuid,
  to_location text, to_client_id uuid, to_work_id uuid,
  quantity numeric NOT NULL,
  inventory_id uuid, user_id uuid DEFAULT auth.uid(), notes text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.andam_inventory (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  number bigint GENERATED BY DEFAULT AS IDENTITY,
  client_id uuid NOT NULL REFERENCES public.clients(id),
  work_id uuid REFERENCES public.works(id),
  inventory_date date NOT NULL DEFAULT current_date,
  user_id uuid DEFAULT auth.uid(), notes text,
  status text NOT NULL DEFAULT 'em_andamento' CHECK (status IN ('em_andamento','finalizado','cancelado')),
  finalized_at timestamptz, finalized_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.andam_inventory_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  inventory_id uuid NOT NULL REFERENCES public.andam_inventory(id) ON DELETE CASCADE,
  item_id uuid NOT NULL REFERENCES public.andam_items(id),
  system_qty numeric NOT NULL DEFAULT 0,
  counted_qty numeric,
  notes text,
  UNIQUE (inventory_id, item_id)
);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.andam_items, public.andam_inventory, public.andam_inventory_items TO authenticated;
GRANT SELECT ON public.andam_stock, public.andam_movements TO authenticated;
GRANT ALL ON public.andam_items, public.andam_stock, public.andam_movements, public.andam_inventory, public.andam_inventory_items TO service_role;

CREATE OR REPLACE FUNCTION public.andam_can(_page text) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT public.is_active_user() AND (public.is_admin() OR public.can_access_page(_page))
$$;

